"""Step 4 - Test generator: structured cases -> executable pytest file.

Only cases with a known template are emitted; the rest stay 'unexecuted'.
Target contract (see README): module exposing make_service(max_attempts) whose
login(email, password) returns {"success": bool, "locked": bool, "message": str},
plus VALID_USER = (email, password).
"""

HEADER = '''"""Auto-generated by req2test - do not edit by hand."""
import importlib
import os

import pytest

target = importlib.import_module(os.environ["REQ2TEST_TARGET"])
EMAIL, PASSWORD = target.VALID_USER
WRONG = "definitely-wrong-password"


@pytest.fixture
def svc():
    return target.make_service(max_attempts=@N@)
'''

T = {
"valid_login": """
    r = svc.login(EMAIL, PASSWORD)
    assert r["success"] is True
    assert r["locked"] is False""",
"wrong_password": """
    assert svc.login(EMAIL, WRONG)["success"] is False""",
"unknown_email": """
    assert svc.login("nobody@example.com", WRONG)["success"] is False""",
"empty_email": """
    assert svc.login("", PASSWORD)["success"] is False""",
"empty_password": """
    assert svc.login(EMAIL, "")["success"] is False""",
"malformed_email": """
    assert svc.login("not-an-email", PASSWORD)["success"] is False""",
"n_minus_1_then_success": """
    for _ in range(@N@ - 1):
        assert svc.login(EMAIL, WRONG)["success"] is False
    assert svc.login(EMAIL, PASSWORD)["success"] is True""",
"lock_at_n": """
    for _ in range(@N@):
        svc.login(EMAIL, WRONG)
    r = svc.login(EMAIL, PASSWORD)
    assert r["success"] is False
    assert r["locked"] is True""",
"stays_locked": """
    for _ in range(@N@):
        svc.login(EMAIL, WRONG)
    for pw in (WRONG, PASSWORD, PASSWORD):
        assert svc.login(EMAIL, pw)["success"] is False""",
"no_user_enumeration": """
    unknown = svc.login("nobody@example.com", WRONG)
    known = svc.login(EMAIL, WRONG)
    assert unknown["message"] == known["message"]""",
"sql_injection": """
    assert svc.login("' OR '1'='1' --", "x")["success"] is False
    assert svc.login(EMAIL, "' OR '1'='1")["success"] is False""",
"password_not_echoed": """
    assert WRONG not in str(svc.login(EMAIL, WRONG))""",
"very_long_input": """
    assert svc.login("a" * 10000 + "@example.com", "p" * 100000)["success"] is False""",
}


def generate(cases, a):
    n = a.parameters.get("max_failed_attempts")
    parts = [HEADER.replace("@N@", repr(n))]
    for c in cases:
        body = T.get(c.template)
        if c.executable and body is None:
            c.executable, c.reason = False, "No test template available"
        if not c.executable:
            continue
        body = body.replace("@N@", str(n))
        name = c.id.lower().replace("-", "_")
        c.code = (f"def test_{name}(svc):\n"
                  f'    """{c.id} [{c.category}] {c.title} | traces: {c.requirement_id}"""'
                  + body + "\n")
        parts.append("\n\n" + c.code)
    return "".join(parts)
